"""ONE GRAVITY (directive FU0, `docs/directives/FU.md`).

The project uses FloatSim's value, `9.81 m/s^2`, read from
`floatfea.io.frames.GRAVITY_MAGNITUDE`. No other gravity literal lives in `floatfea/`
or `scripts/`.

**WHY, AND IT IS R1004.** `floatfea/io/frames.py` declares `GRAVITY_MAGNITUDE = 9.81`
and its own published frames table calls the value out explicitly -- "magnitude 9.81,
FloatSim's value, **not** 9.80665" -- while two measure scripts declared their own
`GRAVITY = 9.80665` and two further sites carried `9.81` as a bare literal. Every force
in the model consumes the frames value; the sea-state screen consumed a different one.
Measured, with each producer run at both values:

* `scripts/measure/f6_results_report.py` -- 2 of 6 published `H/lambda` figures differ
  at the printed 4 dp (`T = 10 s`: `0.1551` against `0.1550`). **No BREAKING verdict
  flips**, so the governing set does not move.
* `scripts/measure/f6a_required_section.py` -- 6 of the 10 lines of
  `results/F6a/required_section.csv` differ (its 6 data rows), **6** JSON field names
  move, and 5 lines of `results/F6a/required_section.md`.
  `implied_root_moment_nm` is `259048069.9214031` against `259136562.01954436`.

**Half B landed in FT2.4 and the three tracked `results/F6a/` deliverables were
regenerated in that commit (BP0), so the paragraph above describes the state BEFORE the
repair.** The field-by-field measurement of what moved, and the two sentences the half-A
prediction above got wrong, are in that commit's message and in the step report, which is
regenerated by rule. **One claim out of it belongs here because it is a claim about this
repository's code rather than about a run**, and
`test_the_SEARCH_reads_no_gravity_at_all` below is that claim as a test instead of a
sentence: `g` never enters the search, so no chosen section, `max_U` or governing clause
could have moved.

Relative size of the original disagreement: `3.416e-04`, which is `9.81 / 9.80665 - 1`.
Wrong absolute numbers in two tracked deliverables, no wrong finding. Under FR1 that is
the second head -- an input accepted and used other than as declared.

**WHY THIS TEST PARSES INSTEAD OF GREPPING.** FU0's own suggested check is
`grep 9.80665 ... returns 0`, and that check is not sufficient for the rule FU0 states:
two of the four sites carried `9.81`, the *right* value as a bare literal, which the grep
cannot see, and after the repair the surviving textual hits are all comments describing
the repair, which the grep *would* see. A float constant is found exactly by reading the
syntax tree and cannot be hidden in a comment or revealed by reformatting.
"""

from __future__ import annotations

import ast
import importlib.util
import math
import sys
from pathlib import Path
from types import ModuleType

from floatfea.io import frames
from floatfea.loads import period_band

ROOT = Path(__file__).resolve().parents[1]
ROOTS = ("floatfea", "scripts")

# The spellings a gravity constant has actually taken in this repository, plus the two
# other common ones. EXACT EQUALITY against this tuple -- there is no window here and no
# epsilon. A detector band such as "any float in 9.7 .. 9.9" would be a tier cutoff in a
# screen, which `CLAUDE.md` treats as a tolerance under another name, and it would
# therefore belong in `floatfea/tolerances.py` with a justification. An enumerated list
# of literals needs neither.
FORBIDDEN: tuple[float, ...] = (9.81, 9.80665, 9.8, 9.807)

# The ONE module permitted to declare the value.
DECLARING = Path("floatfea/io/frames.py")

# **FU0 IS CLOSED AND NOTHING IS EXEMPT, which is the state this mechanism was built to
# reach.** Half A landed in FT2.3; half B -- `scripts/measure/f6a_required_section.py` --
# landed in FT2.4, with the three tracked `results/F6a/` deliverables regenerated in the
# same commit (BP0).
#
# The dict stays, empty, as the declaration that nothing is exempt. The ENTRY had to go
# rather than being emptied in place, because `test_every_exemption_is_STILL_NEEDED`
# asserts that each exempted file still carries the declared hit: an exemption that
# outlives its repair is red, which is how the repair forced the deletion. A guard that
# fails false is fixed or deleted, never extended (EK2).
#
# **R1014 is why an entry carries its LINE AND VALUE and not only a path**, and the shape
# is kept here for the next exemption if there is one. The reverse guard first asserted
# only that an exempted file still carried a forbidden literal AT ALL, so a PARTIAL repair
# -- `9.80665` corrected to `9.81`, still a bare literal -- kept the exemption alive and
# left the leftover unscanned. Measured, three arms: shipped `[(52, 9.80665)]` green,
# partial `[(52, 9.81)]` ALSO green, full repair `[]` red.
EXEMPT_PENDING_FT2_4: dict[Path, list[tuple[int, float]]] = {}


def _sources() -> list[Path]:
    out: list[Path] = []
    for root in ROOTS:
        out.extend(sorted((ROOT / root).rglob("*.py")))
    assert out, "no sources found; the roots moved"
    return out


def _gravity_literals(path: Path) -> list[tuple[int, float]]:
    """Every float constant in `path` equal to one of `FORBIDDEN`, with its line."""
    tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
    found: list[tuple[int, float]] = []
    for node in ast.walk(tree):
        if not isinstance(node, ast.Constant):
            continue
        value = node.value
        # `isinstance(True, int)` is True, so booleans are excluded explicitly.
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            continue
        if any(float(value) == f for f in FORBIDDEN):
            found.append((node.lineno, float(value)))
    return found


def test_NO_gravity_literal_outside_the_declaring_module() -> None:
    """FU0: `floatfea.io.frames` is the single source and nothing else spells it out."""
    offenders: dict[str, list[tuple[int, float]]] = {}
    for path in _sources():
        rel = path.relative_to(ROOT)
        if rel == DECLARING or rel in EXEMPT_PENDING_FT2_4:
            continue
        hits = _gravity_literals(path)
        if hits:
            offenders[rel.as_posix()] = hits
    assert not offenders, (
        "a gravity literal lives outside `floatfea/io/frames.py` (FU0). Read the value "
        "from `floatfea.io.frames.GRAVITY_MAGNITUDE`, or -- for the sea-state screen -- "
        f"call `floatfea.loads.period_band`, which already does: {offenders}"
    )


def test_every_exemption_is_STILL_NEEDED() -> None:
    """An exemption whose file no longer offends is deleted, not carried (EK2).

    This is what stops `EXEMPT_PENDING_FT2_4` becoming a permanent hole. When FT2.4
    repairs half B this test fails, and the only repair for it is removing the entry.
    """
    for rel, declared in EXEMPT_PENDING_FT2_4.items():
        hits = _gravity_literals(ROOT / rel)
        assert hits == declared, (
            f"{rel.as_posix()} is exempted from FU0 for {declared} and its gravity "
            f"literals are now {hits}. EITHER the repair landed, in which case the "
            f"exemption is stale and gets deleted from `EXEMPT_PENDING_FT2_4` (EK2), OR "
            f"the literal moved or changed value, in which case the exemption no longer "
            f"describes what it is covering and the new state is unscanned. A guard that "
            f"accepts 'some literal, somewhere' accepts a PARTIAL repair."
        )


def test_the_SEARCH_reads_no_gravity_at_all() -> None:
    """FU0 half B could not move an answer, and this is why -- as a test, not a sentence.

    The three searches in `scripts/measure/f6a_required_section.py` re-evaluate the API
    clauses on STORED forces. Gravity reaches that file only in the FG4 mass-consistency
    block and the f-line coupling, both of which run after the answers exist, so correcting
    `g` moved reported moment terms and could not move a chosen section, a `max_U` or a
    governing clause -- which is what the regeneration measured.

    **It is a test because it is the load-bearing half of "no conclusion changed".** That
    sentence is FU0's own requirement of the cover note, and a reader has no way to check
    it from a diff of two published files: identical answers are equally consistent with
    "`g` does not reach the search" and with "`g` reaches it and the grid step happened to
    absorb the change". Only the first is true, and only this distinguishes them.
    """
    source = (ROOT / "scripts" / "measure" / "f6a_required_section.py").read_text(encoding="utf-8")
    tree = ast.parse(source)
    searches = {"search_min_wall", "search_min_diameter", "search_min_area"}
    seen: set[str] = set()
    for node in ast.walk(tree):
        if not isinstance(node, ast.FunctionDef) or node.name not in searches:
            continue
        seen.add(node.name)
        names = {inner.id for inner in ast.walk(node) if isinstance(inner, ast.Name)} | {
            inner.attr for inner in ast.walk(node) if isinstance(inner, ast.Attribute)
        }
        offending = sorted(n for n in names if "GRAVITY" in n.upper())
        assert not offending, (
            f"{node.name} references {offending}. The searches must read stored forces "
            f"only: if gravity reaches one of them, correcting it can move a chosen "
            f"section, and FU0's cover note claim that no conclusion changed stops "
            f"following from the regeneration."
        )
        assert not _gravity_literals_in(node), (
            f"{node.name} carries a gravity literal of its own, which is FU0's whole "
            f"subject and is invisible to the name check above."
        )
    assert seen == searches, (
        f"found {sorted(seen)} of {sorted(searches)}; the search functions were renamed "
        f"and this cell is now asserting over fewer of them than it names."
    )


def _gravity_literals_in(node: ast.AST) -> list[tuple[int, float]]:
    """`_gravity_literals`' predicate, over one subtree instead of a whole file."""
    found: list[tuple[int, float]] = []
    for inner in ast.walk(node):
        if not isinstance(inner, ast.Constant):
            continue
        value = inner.value
        if isinstance(value, bool) or not isinstance(value, (int, float)):
            continue
        if any(float(value) == f for f in FORBIDDEN):
            found.append((inner.lineno, float(value)))
    return found


def test_the_declaring_module_declares_FLOATSIMS_value_and_not_the_standard_one() -> None:
    """9.81, not 9.80665. The frames table publishes this distinction explicitly."""
    # not-a-tolerance: FloatSim's own gravity, the quantity this whole file exists to
    # keep single-sourced. Exact equality against the value directive FU0 names; nothing
    # is being allowed to differ by it, and a window here would be the detector band the
