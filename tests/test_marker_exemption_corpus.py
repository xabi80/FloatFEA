"""The exemption window, run against the reviewer's shapes (CB0).

`tests/test_no_tolerance_literals.py` keeps every tolerance in
`floatfea/tolerances.py`. Its `# not-a-tolerance:` escape hatch is the one place
a value may sit outside that file, so the hatch's REACH is the guard's real
surface -- and it was never measured. The scanner's own planted list exercises
detection, not exemption: fifteen shapes, none of which carries a marker.

**Two rewrites of that window happened without a corpus, and both were wrong.**
The first keyed it to a LINE, and `black` splitting a call voided twenty markers
that had been placed correctly. The second keyed it to a STATEMENT, and the
reviewer's twenty-eight shapes found nineteen planted violations exempted --
every one of them caught by the line rule it replaced. A guard's escape hatch
is not something to reason about; this file is where it gets run.

THE CORPUS IS THE REVIEWER'S. `tests/corpus/tolerance_marker_exemptions.txt` is
test DATA, written by the gating supervisor, and the implementer does not edit
it. Each entry is a complete module and a required verdict:

    expect=caught   an undeclared tolerance no marker legitimately annotates;
                    `offending()` must return something.
    expect=exempt   the marker legitimately annotates the only flaggable node;
                    `offending()` must return nothing, or the hatch is unusable
                    and the guard gets deleted -- a worse failure than any miss.

**ESCAPES ARE DERIVED, NOT SKIPPED, NOT `xfail`ed, AND NOT DECLARED.**
`CLAUDE.md` forbids `skip` and `xfail` outright, and the first version of this
file reached for `xfail` -- the forbidden mechanism wearing a reason. What
replaced it was a hand-written map of names, and R341 showed that a map is a
convention rather than a check: a provenance string anyone can type clears a
genuine regression, and the reviewer demonstrated exactly that. What is here
now reads the corpus's own `measured=` field, which records what the shipped
scanner did at plant time and which only the reviewer can write.

WHAT THAT BUYS, STATED AT THE THIRD ATTEMPT, because the first two versions
of this paragraph each claimed more than the code did. The fields that decide
-- `expect` and `measured` -- are the reviewer's to write. They reach the
decision through `_entries()`, which is mine, and `_entries()` can drop an
entry (R351) or rewrite a field on the way through (R359); both were
demonstrated, and both left the suite green with a real regression planted.

So the file is read TWICE, by readers that share nothing but the path, and
the parser's output is put back into the file's own form and compared to the
bytes. NOT a list of the fields that matter: that list was wrong twice, and
each time the next edit went into something it did not mention -- the row
itself, then the source module the scanner runs on. A round trip has nothing
to leave out, and a field added later is covered the day it is added.

What it buys is that an edit in the parser has to be made identically in two
places to stay invisible, and one of those places exists for no other
purpose. It is not a proof that no such edit is possible. The rule is set out
above `_entries()`.
"""

