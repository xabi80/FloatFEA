#!/usr/bin/env python
"""FG5: the F6a required-section deliverable, generated.

    python scripts/measure/f6a_report.py

Every figure comes from `results/F6a/required_section.json`, which
`f6a_required_section.py` writes, or from the built model. Nothing is typed into the
document -- F6's R739/R747/R752/R753 were four published sentences that were false, each a
figure a reader could not regenerate, and F6a inherits the habit rather than the lesson's
cost.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))

from floatfea.basis import E_STEEL, FY_S355, RHO_STEEL  # noqa: E402
from floatfea.checks.api_wsd import CM_JOINT_TRANSLATION  # noqa: E402
from floatfea.model.platform import ARM_OUTER_DIAMETER, ARM_WALL  # noqa: E402

SEARCH_LABEL = {
    "i_min_wall_at_D_2.5": "(i) `D = 2.5 m` fixed, minimum `t`",
    "ii_min_diameter_at_t_180mm": "(ii) `t = 180 mm` fixed, minimum `D`",
    "iii_min_area": "(iii) minimum **area** over the grid",
}
GROUP_LABEL = {"platform": "platform arms (4)", "hubs": "hub arms (12)"}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument(
        "--answers", type=Path, default=ROOT / "results" / "F6a" / "required_section.json"
    )
    ap.add_argument("--out", type=Path, default=ROOT / "results" / "F6a" / "required_section.md")
    ap.add_argument("--premise", type=Path, default=ROOT / "results" / "F6a" / "premise_check.json")
    args = ap.parse_args(argv)

    blob = json.loads(args.answers.read_text(encoding="utf-8"))
    answers, cont = blob["answers"], blob["continuum"]
    found = [a for a in answers if a.get("found")]
    premise = json.loads(args.premise.read_text(encoding="utf-8"))

    # R781: F6's stand-in utilisation, READ from the published CSV rather than typed.
    util_rows = [
        ln
        for ln in (ROOT / "docs" / "F6_utilisation.csv").read_text(encoding="utf-8").splitlines()
        if ln[:1] != "#"
    ]
    import csv as _csv

    standin_u = max(float(r["utilisation_K2"]) for r in _csv.DictReader(util_rows))
    out: list[str] = []
    w = out.append

    w("# FloatFEA — the section each arm group needs to pass")
    w("")
    w("**INDICATIVE.** A stand-in tube for a truss of undecided depth; placeholder masses;")
    w("one heading, 0°; `F_y` assumed. Generated by `scripts/measure/f6a_report.py` from")
    w("`scripts/measure/f6a_required_section.py`'s and `f6a_premise_check.py`'s own JSON")
    w("output. **No MEASURED figure is typed into this document or its generator** — what")
    w("is written literally is the declared inputs and the clause's own constants, each")
    w('named as such where it appears. An earlier version said "no figure is typed" and')
    w("four measured figures in it were string literals in the generator, all four correct")
    w("and none readable from anything.")
    w("")
    w(f"Clauses as F6: API RP 2A-WSD, `F_y = {FY_S355/1e6:.0f} MPa`, `E = {E_STEEL/1e9:.0f} GPa`,")
    w(f"`K = 2.0`, `C_m = {CM_JOINT_TRANSLATION}`, **no one-third increase**. Loads: F4's")
    w("governing envelope (EZ2/FA0 — the four in-band periods), per instant, at ROOT, MID")
    w("and TIP. A candidate outside the clause's own ranges is **refused, not")
    w("extrapolated**.")
    w("")
    w(
        f"For comparison, F6's stand-in is `D = {ARM_OUTER_DIAMETER} m`, "
        f"`t = {ARM_WALL * 1000:.0f} mm`,"
    )
    w(f"at which the worst station reaches `U = {standin_u:.5f}`.")
    w("")

    w("## The table")
    w("")
    w("| group | search | D [m] | t [mm] | D/t | A [m²] | W [m³] | max U | U(K=1) | U(C_m=1) |")
    w("|---|---|---|---|---|---|---|---|---|---|")
    for a in found:
        w(
            f"| {GROUP_LABEL[a['group']]} | {SEARCH_LABEL[a['search']]} | {a['D_m']:.1f} | "
            f"{a['t_m']*1000:.0f} | {a['D_over_t']:.2f} | {a['A_m2']:.4f} | {a['W_m3']:.4f} | "
            f"**{a['max_U']:.4f}** | {a['U_K1']:.4f} | {a['U_Cm1']:.4f} |"
        )
    w("")
    w("| group | search | governing member-station | T [s] | clause | branch | form |")
    w("|---|---|---|---|---|---|---|")
    for a in found:
        w(
            f"| {GROUP_LABEL[a['group']]} | {SEARCH_LABEL[a['search']]} | "
            f"`{a['worst_member']}` {a['worst_station']} | {a['worst_period_full_s']} | "
            f"{a['worst_clause']} | {a['worst_axial_branch']} | {a['worst_interaction_form']} |"
        )
    w("")

    w("## Mass consistency — the key finding")
    w("")
    w(f"The steel the required section is made of, at `ρ = {RHO_STEEL:.0f} kg/m³`, against")
    w("the arm line mass the model assumed for it.")
    w("")
    w("| group | search | ρ·A_req [t/m] | assumed μ [t/m] | ratio | consistent? |")
    w("|---|---|---|---|---|---|")
    for a in found:
        ratio = a["mass_ratio"]
        w(
            f"| {GROUP_LABEL[a['group']]} | {SEARCH_LABEL[a['search']]} | "
            f"{a['steel_line_mass_kg_per_m']/1000:.3f} | "
            f"{a['assumed_mu_kg_per_m']/1000:.3f} | **{ratio:.3f}** | "
            f"{'NO — the section outweighs its own assumed mass' if ratio > 1.0 else 'yes'} |"
        )
    w("")

    bad = [a for a in found if a["mass_ratio"] > 1.0]
    if bad:
        w("**For the rows marked NO, the section needed to pass outweighs the mass assumed")
        w("for it, so the mass basis and the section are inconsistent.** The model holds the")
        w("deck's `μ` fixed and back-computes an equivalent density, so a heavier section")
        w("carries no more self-weight in the solve — which is exactly why the search")
        w("converges and exactly why the answer cannot be taken at face value. What that")
        w("section would really weigh implies more self-weight, hence a larger required")
        w("section, and so on.")
        w("")
        w("**This is not iterated here.** Closing that loop needs a mass budget, which is")
        w("increment 2.")
        w("")
        # C102: THE COLUMN THAT WAS HERE CARRIED NO INFORMATION. It was headed
        # "x the mu-basis term" and equalled
        #     (rho A_req g L^2/2) / (mu g L^2/2) = rho A_req / mu
        # identically, so the mass-ratio column of the table above appeared a second
        # time in the document looking like a different quantity. The ratio that is not
        # a restatement is the one in the block below, which carries the remainder mass
        # -- so the table is dropped and the block does the work.
        w("**How big the inconsistency is, and the arm-weight term alone UNDERSTATES it.**")
        w("The published static root moment carries two independent loads: the arm's own")
        w("uniform weight, and the body's remainder mass at its own node. **Only the first")
        w("moves with the section.** So hold the remainder at its published value and scale")
        w("the arm:")
        w("")
        w("```")
        w(
            f"  g L^2 / 2                    = {cont['arm_coeff_nm_per_kg_per_m']:.6e}"
            " N.m per (kg/m)"
        )
        w(f"  published static root |My|   = {cont['published_static_root_nm']:.6e} N.m")
        w(
            f"  of which the remainder's share = {cont['remainder_share_nm']:.6e} N.m"
            f"  ({cont['remainder_fraction_of_published']:.1%}), constant in the section"
        )
        w("")
        w(
            f"{'search':30s} {'mu implied':>11s} {'arm term':>14s} "
            f"{'+ remainder':>14s} {'/published':>11s}"
        )
        for a in found:
            if a["group"] != "platform" or "model_implied_root_moment_nm" not in a:
                continue
            w(
                f"{a['search']:30s} {a['steel_line_mass_kg_per_m']:11.3f} "
                f"{a['implied_root_moment_nm']:14.6e} "
                f"{a['model_implied_root_moment_nm']:14.6e} "
                f"{a['model_implied_over_published']:11.3f}"
            )
        w("```")
        w("")
        over = [
            a
            for a in found
            if a.get("model_implied_over_published", 0.0) > 1.0 and a["group"] == "platform"
        ]
        if over:
            worst_over = max(over, key=lambda a: a["model_implied_over_published"])
            w(
                f"**{len(over)} of the three platform answers imply a static root moment"
                f" ABOVE the present total**, the worst by"
                f" `{(worst_over['model_implied_over_published'] - 1.0) * 100:.0f}%` —"
            )
            w("before any wave load, and before the larger section that extra weight would")
            w("itself require. **An earlier version of this document compared the arm-weight")
            w("term alone against the published total and reported a smaller figure, which")
            w("understated it, and showed answer (ii) as under the total when it is over.**")
            w("That is the size of the circularity increment 2 has to break, and it is why")
            w("this increment stops here rather than iterating.")
            w("")
            w("**And the two-point fit that looks like the obvious way to measure this is")
            w("the wrong instrument.** Fitting `M_root = a·μ + b` from two")
            w("`measurement_fraction` builds gives a **negative** `a`: raising `f` takes mass")
            w("off the remainder node and spreads it along the arm, and the remainder's lever")
            w("is larger per kilogram, so the f-line's slope is not the arm-weight")
            w("coefficient. The sign is what says so.")
            w("")
    w("## Findings")
    w("")
    plat = {a["search"]: a for a in found if a["group"] == "platform"}
    hubs = {a["search"]: a for a in found if a["group"] == "hubs"}
    w("**(i) Every search converges, so a passing section exists in the declared grid** —")
    w("which F6 could not say. The platform arms need the most steel by every measure.")
    w("")
    if "i_min_wall_at_D_2.5" in plat:
        a = plat["i_min_wall_at_D_2.5"]
        w(f"**(ii) At the recorded diameter the platform arm needs `t = {a['t_m']*1000:.0f} mm`**,")
        w(f"against the recorded `{ARM_WALL*1000:.0f} mm` — `D/t = {a['D_over_t']:.2f}`, a")
        w("very thick-walled tube, and its steel weighs")
        w(f"`{a['mass_ratio']:.3f}×` the mass assumed for it. Holding `D` is the most")
        w("expensive of the three constraints.")
        w("")
    if "iii_min_area" in plat and "iii_min_area" in hubs:
        pa, ha = plat["iii_min_area"], hubs["iii_min_area"]
        w("**(iii) The minimum-area answers are the only mass-consistent ones**, and both")
        w(f"sit at `D = {pa['D_m']:.1f} m` — **the upper bound of the declared grid**. That is")
        w("a boundary answer and should be read as one: the true minimum-area tube may lie")
        w(
            f"outside `D ≤ {cont['grid_D_max_m']:.1f} m`, and the search cannot say, because "
            "FG3 fixed the range."
        )
        w("")
        shape = cont["boundary_shape"]["platform"]
        w("**Which direction that matters in, and how fast — because the bound is not a")
        w("detail here.** The least area a passing section needs falls as the bound rises,")
        w(
            f"by {float(shape['fall_over_the_range_relative']):.1%} across the range, so "
            "RAISING the bound would only make this answer lighter and more"
        )
        w("consistent. Lowering it does the opposite, and the mass-consistency verdict does")
        w("not survive far:")
        w("")
        sweep = cont["boundary_sweep"]["platform"]
        cross = cont["boundary_crossing"]["platform"]
        w("| `D` [m] | min passing `A` [m²] | `ρ·A / μ` | mass-consistent? |")
        w("|---|---|---|---|")
        for row in sweep:
            if not row["passes"]:
                continue
            if round(float(row["D_m"]) * 10) % 10 and float(row["D_m"]) != float(
                cross["largest_D_with_ratio_above_1"]
            ):
                continue
            ratio = float(row["rho_A_over_mu"])
            w(
                f"| {float(row['D_m']):.1f} | {float(row['A_m2']):.4f} | "
                f"**{ratio:.3f}** | {'yes' if ratio <= 1.0 else 'NO'} |"
            )
        w("")
        first = next(r for r in sweep if r["passes"])
        w(
            f"Nothing in the grid passes below `D = {float(first['D_m']):.1f} m` for this "
            f"group. The ratio is above 1.0 up to and including "
            f"`D = {float(cross['largest_D_with_ratio_above_1']):.1f} m` and at or below it "
            f"from `D = {float(cross['smallest_D_with_ratio_below_1']):.1f} m`, so **had FG3"
        )
        w(
            f"written `D ≤ {float(cross['largest_D_with_ratio_above_1']):.1f} m` this "
            "finding would have read the other way** — every answer inconsistent, and no"
        )
        w("mass-consistent section anywhere in the declared range. The conclusion is a")
        w("function of the bound and the bound was given, not derived.")
        w("")
        w(
            f"The sequence is **not monotone**: {int(shape['rises'])} of "
            f"{int(shape['steps'])} steps in `D` cost MORE area than the diameter below "
            "them, the"
        )
        w(
            f"largest by {float(shape['largest_rise_relative']):.2%}, because the "
            f"{float(cont['grid_t_step_m'])*1000:.0f} mm wall step quantises the answer "
            "and a"
        )
        w(
            f"{float(cont['grid_D_step_m']):.1f} m step in `D` can land on a thicker "
            "admissible wall. The trend falls; the"
        )
        w("grid does not, and an earlier version of this paragraph said it did. What a bound")
        w("selects is the best section at or below it, and that does fall — which is the")
        w("claim the paragraph needs and the one it now makes.")
        w(f"Their `D/t` are `{pa['D_over_t']:.2f}` and `{ha['D_over_t']:.2f}` — slender, where")
        w("§ 3.2.2(b)'s local-buckling reduction is live rather than inert as it is on F6's")
        w("stand-in.")
        w("")
    if "i_min_wall_at_D_2.5" in plat and "ii_min_diameter_at_t_180mm" in plat:
        p1, p2 = plat["i_min_wall_at_D_2.5"], plat["ii_min_diameter_at_t_180mm"]
        w("**(iv) BENDING GOVERNS THE PLATFORM ARMS, SO THE BINDING QUANTITY IS `W` AND NOT")
        w("`A` — and the number that transfers is the continuum one, not the grid's.**")
        w("")
        w("```")
        w(
            f"bending is {cont['bending_fraction_of_U']:.5%} of U at the governing station "
            f"({cont['governing_station']}, T = {cont['governing_period_s']} s),"
        )
        w("so the requirement is a section modulus:")
        w(
            f"  W_req = M_res / F_b = {cont['M_res_nm']:.6e} / {cont['F_b_compact_pa']:.6e}"
            f" = {cont['W_req_continuum']:.6f} m^3    (F_b branch: {cont['F_b_branch']})"
        )
        w("")
        w("inverting max U = 1 in each constrained search, instead of sampling the grid:")
        w(
            f"  D = 2.5 m fixed : t* = {cont['exact_t_at_D_2.5_m']*1000:.4f} mm"
            f"  -> W* = {cont['exact_W_at_D_2.5']:.8f}"
        )
        w(
            f"  t = 180 mm fixed: D* = {cont['exact_D_at_t_180mm']:.6f} m"
            f"  -> W* = {cont['exact_W_at_t_180mm']:.8f}"
        )
        w(
            f"  the two EXACT requirements differ by {cont['exact_spread_relative']:.3e};"
            f" the two GRID answers by {cont['published_spread_relative']:.3e}"
        )
        w(
            f"  one grid step in W at D = 2.5 m is {cont['grid_step_W_at_D_2.5']:.6f} m^3,"
            f" so that agreement is "
            f"{cont['published_spread_relative'] / (cont['grid_step_W_at_D_2.5'] / p1['W_m3']):.1e}"
            " of ONE step"
        )
        w("```")
        w("")
        w("**The mechanism is a measurement; the six-figure agreement was not.** Both")
        w("constrained answers sit in the same compact branch, so `F_b` is identically")
        w("`0.75 F_y` and the required `W` is the same quantity in both searches — that part")
        w("is real, and it is why two searches constrained in different variables pay")
        w(f"`{p1['A_m2']/p2['A_m2']:.3f}×` different amounts of steel for it. **But the")
        w("mechanism is only good to the spread above, and an earlier version of this")
        w("document published the grid's much closer agreement as though it were the")
        w("structure.** A reader transferring six figures to a truss would have been")
        w("over-trusting the measurement by orders of magnitude.")
        w("")
        w(f"**Transfer `W_req ≈ {cont['W_req_continuum']:.4f} m³`, and only with its")
        w(f"allowable**: it is tied to `F_b = {cont['F_b_compact_pa']/1e6:.2f} MPa`, the")
        w("compact branch. Answer (iii) does **not** share it — at")
        if "iii_min_area" in plat:
            p3 = plat["iii_min_area"]
            w(
                f"`D/t = {p3['D_over_t']:.2f}` § 3.2.3 reduces `F_b`, so its `W` is"
                f" `{p3['W_m3']:.4f}` against the compact requirement above."
            )
        w("")
        w("`W` grows with `D²t` and `A` with `Dt`, so diameter buys section modulus far more")
        w("cheaply than wall thickness — which is why (iii) finds so much less area at a")
        w("larger diameter, and is the part that carries over to a truss, which buys `W`")
        w("with depth the same way.")
        w("")
        w("The hub arms are governed by § 3.3.1 in **tension** at every answer, so there it")
        w("is `A` that binds and the three answers share no `W` — the control on the")
        w("sentence above rather than a second example of it.")
        w("")
    w("**(v) Neither modelling lever moves the answer**, as in F6: compare the `U(K=1)` and")
    w("`U(C_m=1)` columns with `max U`. Section 3.3.2 takes the larger of its amplified and")
    w("simple forms and the simple form carries neither `F_a` nor `C_m`.")
    w("")
    w("**(vi) The premise the search rests on is verified, and it is NARROWER than it was")
    w("first stated.** The claim was that section choice does not move the member forces.")
    w("On the static case that is true to round-off; on the dynamic case **the forces do")
    w("move**, and what does not move is `max U` — the quantity the search's answer")
    w("depends on — after re-selecting which instant governs at the sized section.")
    w("")
    w("```")
    stations = next((g["stations"] for g in premise.get("static", {}).values()), None)
    w(
        f"STATIC, at every one of the answers above -- worst relative change over all "
        f"{stations} member-stations and six components, and max U recomputed from the "
        "rebuilt forces:"
    )
    for search, got in sorted(premise.get("static", {}).items()):
        us = ", ".join(f"{g}={u:.6f}" for g, u in sorted(got["max_u_from_rebuilt_static"].items()))
        w(f"  {search:28s} rel {got['worst_relative_change']:.6e}   maxU {us}")
    if premise.get("dynamic"):
        w("")
        w("DYNAMIC, the increment re-solved at the sized section:")
        for search, got in sorted(premise["dynamic"].items()):
            w(
                f"  {search:28s} worst component rel "
                f"{got['worst_component_relative_change']:.6e}"
            )
            for g, d in sorted(got["max_u_change"].items()):
                w(
                    f"  {'':28s} {g:9s} max U {got['max_u_shipped'][g]:.6f} -> "
                    f"{got['max_u_sized'][g]:.6f}   change {d:.3e}"
                )
    w("```")
    w("")
    w("**The mechanism, because the first explanation was wrong.** It said the dynamic")
    w("increment comes from FloatSim's multipliers and each body's d'Alembert field, and")
    w("the field reads `μ`, which is held — so no section could reach it. But the field is")
    w("an acceleration, and what turns it into a load is `M_e @ a_e` with the consistent")
    w("element mass matrix, whose rotary terms are `ρ_eq·I = μ·r²`: **`r` moves with the")
    w("section even though `μ` does not.** `scripts/measure/f6a_premise_check.py --dynamic`")
    w("is the command, and it also reports the two earlier normalisations that divided")
    w("noise by noise before the static figure was trustworthy.")
    w("")
    w("**What this does not answer:** the real truss, the mass budget, any heading but 0°,")
    w("and whether `F_y = 355 MPa` is the grade. The label at the top is the whole of what")
    w("these numbers are.")
    w("")
    w("---")
    w("")
    w("Generated by `scripts/measure/f6a_report.py` from")
    w("`results/F6a/required_section.json`; the search is")
    w("`scripts/measure/f6a_required_section.py` and the premise check is")
    w("`scripts/measure/f6a_premise_check.py`.")

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(out) + "\n", encoding="utf-8", newline="\n")
    print(f"  wrote {args.out.relative_to(ROOT).as_posix()} ({len(out)} lines)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
