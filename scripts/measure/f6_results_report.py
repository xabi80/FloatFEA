def _read_csv(path: Path) -> list[dict[str, str]]:
    lines = [ln for ln in path.read_text(encoding="utf-8").splitlines() if ln[:1] != "#"]
    return list(csv.DictReader(lines))


def _steepness(period_s: float, height_m: float) -> float:
    """`H / lambda` in deep water, `lambda = g T^2 / (2 pi)`."""
    return height_m / (GRAVITY * period_s * period_s / (2.0 * math.pi))


def _band(height_m: float) -> tuple[float, float]:
    """DNV practice: `sqrt(6.5 H) <= T <= sqrt(11 H)`."""
    return math.sqrt(6.5 * height_m), math.sqrt(11.0 * height_m)


def _section() -> dict[str, float]:
    built = build_superstructure()
    sec = built.bodies[0].members[0].section
    d_outer = _outer_diameter(sec)
    wall = 0.5 * (d_outer - math.sqrt(d_outer * d_outer - 4.0 * float(sec.A) / math.pi))
    return {
        "D": d_outer,
        "t": wall,
        "A": float(sec.A),
        "I": float(sec.I_y),
        "W": 2.0 * float(sec.I_y) / d_outer,
        "Wt": 2.0 * float(sec.J) / d_outer,
        "r": math.sqrt(float(sec.I_y) / float(sec.A)),
    }


def _elastic_local_buckling_crossover(fy_mpa: float) -> float | None:
    """The `D/t` at which section 3.2.2(b)'s ELASTIC term starts to govern, or None.

    `F_xe = 2 C E t / D = 2 C E / (D/t)` falls as `D/t` rises; the inelastic expression
    `F_y [1.64 - 0.23 (D/t)^(1/4)]` falls far more slowly. So the elastic term governs
    above a crossover, and the question is whether that crossover is inside the clause's
    own `D/t <= 300`.
    """
    fy = fy_mpa * 1.0e6

    def elastic_governs(d_t: float) -> bool:
        f_xe = 2.0 * ELASTIC_LOCAL_BUCKLING_C * E_STEEL / d_t
        return f_xe < fy * (1.64 - 0.23 * d_t**0.25)

    if not elastic_governs(DT_CLAUSE_MAX):
        return None
    lo, hi = LOCAL_BUCKLING_DT, DT_CLAUSE_MAX
    for _ in range(200):
        mid = 0.5 * (lo + hi)
        if elastic_governs(mid):
            hi = mid
        else:
            lo = mid
    return hi


def _shown(path: Path) -> str:
    """`path` relative to the repo when it is inside it, absolute when it is not.

    R756's gate regenerates this document into a TEMPORARY DIRECTORY and byte-compares two
    runs, so `--out` is legitimately outside the tree and `relative_to(ROOT)` raised there.
    A generator that cannot be pointed at a scratch path cannot be checked for determinism
    at all, which is part of why the plan's regeneration gate went unasserted for so long.
    """
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def _run_gate(node_ids: tuple[str, ...]) -> tuple[str, str]:
    """Run exactly these node ids and return (status, pytest's own counts).

    **THE WALL-CLOCK TIME IS STRIPPED, AND THE REASON IS A GATE (R756).** The locked plan
    requires that this deliverable "regenerates identically from stored results". Pasting
    pytest's summary verbatim broke that on eight lines of 457 -- the counts are
    deterministic and the timings are not, so a second run of the same tree produced a
    different document and nothing said so. The counts are what the row claims; the
    duration was never part of the claim.
    """
    proc = subprocess.run(
        [sys.executable, "-m", "pytest", *node_ids, "-q", "-p", "no:randomly", "--tb=no"],
        capture_output=True,
        text=True,
        cwd=ROOT,
    )
    tail = [ln for ln in proc.stdout.splitlines() if " passed" in ln or " failed" in ln]
    counts = tail[-1].split(" in ")[0] if tail else "?"
    return ("pass" if proc.returncode == 0 else "FAIL"), counts


